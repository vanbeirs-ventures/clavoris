-- Didit KYC integration (replaces Sumsub for identity verification of new users).
-- Profile gets a provider-neutral KYC session reference + decision summary;
-- webhook events are stored idempotently in clv_kyc_events.

alter table public.clv_profiles
  add column if not exists kyc_provider text,
  add column if not exists kyc_session_id text,
  add column if not exists kyc_session_number bigint,
  add column if not exists kyc_summary jsonb;

create index if not exists clv_profiles_kyc_session_idx on public.clv_profiles (kyc_session_id);

create table if not exists public.clv_kyc_events (
  id bigint generated by default as identity primary key,
  provider text not null default 'didit',
  event_id text not null,
  webhook_type text,
  session_id text,
  user_id uuid references public.clv_profiles(id) on delete set null,
  status text,
  environment text,
  payload jsonb not null,
  received_at timestamptz not null default now(),
  processed_at timestamptz
);
create unique index if not exists clv_kyc_events_event_uq on public.clv_kyc_events (provider, event_id);
create index if not exists clv_kyc_events_user_idx on public.clv_kyc_events (user_id, received_at desc);
create index if not exists clv_kyc_events_session_idx on public.clv_kyc_events (session_id);

alter table public.clv_kyc_events enable row level security;
grant select, insert, update, delete on table public.clv_kyc_events to service_role;
revoke all on table public.clv_kyc_events from anon, authenticated;
